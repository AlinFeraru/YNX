-- UI labels are created before VARIABLES_LOADED on some WoW 1.12 clients.
-- Keep their English source so saved languages can be applied after loading.
YNXLocalTextRefs = {};
function YNX_RegisterFont(font,english)
    if font and type(english)=="string" then YNXLocalTextRefs[font]=english end
    return font;
end
function YNX_RefreshStaticTexts()
    for font,english in pairs(YNXLocalTextRefs) do
        if font and font.SetText then
            -- SavedVariables can load after the initial label creation. Switch
            -- font faces as well as text so non-Latin glyphs appear on reload.
            if YNX_RefreshFont and font.GetFont then
                local _,size,flags=font:GetFont();
                if type(size)=="number" then YNX_RefreshFont(font,size,flags or "OUTLINE") end
            end
            font:SetText(YNX_L(english))
        end
    end
end
-- The English source text is the canonical key. Missing translations safely
-- fall back to English instead of rendering an empty string.
local YNXDynamicPrefixes={
    "Current: ","Since run start: ","Page ","Current class: ",
    "ACTIVE: ","SAVED: ","Profile ","Last change: ",
    "Run DPS: ","GOALS: ","Preset code: ","Saved: ",
    "Rank ","Result: ","Gold ","Total damage: ","From ",
    "Tooltip reader: ","Phase: ","Pick ","Bar colour: ",
    "ICON ART: ","HUD FONT: ","HUD WIDTH: "
};
function YNX_L(value)
    if type(value)~="string" then return value end
    local d=ABASettingsDB;
    local lang=(type(d)=="table" and d.language) or "en";
    if lang=="en" then return value end
    local words=YNXLocales[lang];
    if type(words)~="table" then return value end
    local translated=words[value];
    if translated then return translated end
    -- For dynamic fields keep their numeric/data suffix unchanged.
    for i=1,table.getn(YNXDynamicPrefixes) do
        local prefix=YNXDynamicPrefixes[i];
        if string.sub(value,1,string.len(prefix))==prefix and words[prefix] then
            return words[prefix]..string.sub(value,string.len(prefix)+1) end
    end
    return value;
end

